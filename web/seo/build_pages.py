def cta_href(slug):
    params = CTA.get(slug)
    return "/?" + urlencode(params, quote_via=quote) if params else "/"


def render(p):
    title_by_slug = {q["slug"]: q["h1"] for q in PAGES}
    body = ""
    for h2, blocks in p["sections"]:
        body += f"<h2>{h2}</h2>"
        for b in blocks:
            body += TOK[b]() if b in TOK else f"<p>{b}</p>"
    faq = "".join(f"<details><summary>{q}</summary><p>{a}</p></details>" for q, a in p["faq"])
    rel = " · ".join(f'<a href="/{s}/">{title_by_slug[s]}</a>' for s in p["related"])
    url = f"{SITE}/{p['slug']}/"
    ld = ('{"@context":"https://schema.org","@type":"BreadcrumbList","itemListElement":['
          f'{{"@type":"ListItem","position":1,"name":"BannerBot","item":"{SITE}/"}},'
          f'{{"@type":"ListItem","position":2,"name":"{p["h1"]}","item":"{url}"}}]}}')
    return f"""<!DOCTYPE html>
<html lang="ru">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>{p['title']}</title>
<meta name="description" content="{p['desc']}">
<link rel="canonical" href="{url}">
<link rel="icon" href="/favicon.ico" sizes="48x48">
<link rel="icon" href="/favicon.svg" type="image/svg+xml" sizes="any">
<link rel="apple-touch-icon" href="/apple-touch-icon.png">
<meta property="og:type" content="article"><meta property="og:locale" content="ru_RU"><meta property="og:site_name" content="BannerBot">
<meta property="og:title" content="{p['title']}"><meta property="og:description" content="{p['desc']}"><meta property="og:url" content="{url}">
<meta property="og:image" content="{SITE}/static/og/og-image.jpg">
<script type="application/ld+json">{ld}</script>
<style>{CSS}</style>
</head>
<body><main>
<p class="bc"><a href="/">BannerBot</a> › {p['h1']}</p>
<h1>{p['h1']}</h1>
<p>{p['lead']}</p>
{body}
<h2>Частые вопросы</h2>{faq}
<p style="margin-top:32px"><a class="btn" href="{cta_href(p['slug'])}">Собрать макет — 299 ₽</a></p>
<p class="bc">Читайте также: {rel}</p>
<p class="bc"><a href="/requisites.html">Реквизиты и оплата</a></p>
</main></body></html>
"""


def main():
    for p in PAGES:
        d = OUT / p["slug"]
        d.mkdir(exist_ok=True)
        (d / "index.html").write_text(render(p), encoding="utf-8")
    urls = [f"{SITE}/", f"{SITE}/requisites.html"] + [f"{SITE}/{p['slug']}/" for p in PAGES]
    body = "".join(f"  <url>\n    <loc>{u}</loc>\n  </url>\n" for u in urls)
    (OUT / "sitemap.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + body + "</urlset>\n",
        encoding="utf-8")


if __name__ == "__main__":
    main()
