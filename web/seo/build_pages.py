def cap_mm(width_mm, chars, k=0.6):
    """Оценка высоты прописных (мм) для строки из chars знаков: поля 30 мм, кегль=ширина/(знаки*k), прописные 0,7 кегля."""
    return 0.7 * (width_mm - 2 * SAFE_MM) / (chars * k)


