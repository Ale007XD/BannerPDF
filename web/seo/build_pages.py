def eyelets(w, h, step):
    return 2 * (math.ceil(w / step) + math.ceil(h / step))


def table(head, rows):
    th = "".join(f"<th>{c}</th>" for c in head)
    tr = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows)
    return f'<div class="tw"><table><tr>{th}</tr>{tr}</table></div>'


